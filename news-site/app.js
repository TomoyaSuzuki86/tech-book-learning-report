function renderChips(){
 chips.innerHTML = categories.map(c=>`<button class="chip ${c===activeCategory?"active":""}" data-category="${c}">${c}</button>`).join("");
 chips.querySelectorAll(".chip").forEach(b=>b.addEventListener("click",()=>{activeCategory=b.dataset.category;renderChips();renderCards()}));
}
function renderCards(){
 const q = search.value.trim().toLowerCase();
 const rows = episodes.filter(e => (activeCategory==="すべて"||e.category===activeCategory) && [e.title,e.summary,e.category].join(" ").toLowerCase().includes(q));
 grid.innerHTML = rows.length ? rows.map(e=>`
 <article class="card" data-id="${e.no}" tabindex="0" role="button" aria-label="第${e.no}回を読む">
  <div class="card-top"><span class="category">${e.category}</span><span>${e.date}</span></div>
  <h3>#${String(e.no).padStart(2,"0")} ${e.title}</h3>
  <p>${e.summary}</p>
  <span class="read">READ DIALOGUE →</span>
 </article>`).join("") : '<div class="empty">該当する討論がありません。</div>';
 grid.querySelectorAll(".card").forEach(card=>{
   const open=()=>openEpisode(Number(card.dataset.id));
   card.addEventListener("click",open);
   card.addEventListener("keydown",e=>{if(e.key==="Enter"||e.key===" "){e.preventDefault();open()}});
 });
}
function openEpisode(id){
 const e=episodes.find(x=>x.no===id); if(!e)return;
 content.innerHTML=`
 <div class="article-meta"><span>#${String(e.no).padStart(2,"0")}</span><span>${e.date}</span><span>${e.category}</span></div>
 <h2>${e.title}</h2>
 <p class="article-summary">${e.summary}</p>
 ${e.dialogue.map(([who,text])=>`<div class="exchange ${who==="奏汰"?"kanata":"hinata"}"><div class="who">${who}</div><p>${text}</p></div>`).join("")}
 <div class="takeaway"><strong>この回の核心</strong><br>${e.takeaway}</div>`;
 dialog.showModal();
 history.replaceState(null,"","#episode-"+id);
}
